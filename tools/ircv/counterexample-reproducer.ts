/**
 * IRCV component 6 — counterexample reproduction.
 *
 * Reads a textual Tamarin-style counterexample description, generates an
 * executable adversarial execution script, runs it against the TypeScript
 * implementation plus the local x402 facilitator, and compares the expected
 * rejection to the observed one.
 *
 * Built-in sample: "old identity epoch accepted after revocation". RCLB is
 * present in this repository, so this scenario is genuinely executable — not
 * a schema-only demo.
 */

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

export const ARTIFACT_DIR = resolve(import.meta.dir, "../../experiments/novelty/ircv");

export const BUILTIN_COUNTEREXAMPLE = `Tamarin-style counterexample description (textual, not a parsed Tamarin trace):
  theory CLBAligned / RCLB extension (packages/clb-core/src/epochs.ts)
  lemma: revocation-aware binding accepts only CURRENT epochs
  trace:
    Anchor_Principal(H)
    DelegatedB(H, C_t, E_I=1, E_M=1, T_expiry=1800000000, N=0x11..11)
    Revocation: authority advances identity epoch E_I to 2
    Settlement presents the SAME C_t with E_I=1 at t=1700000000
  expected: REJECT (IDENTITY_EPOCH_STALE)
  question: does the implementation accept the old identity epoch?
`;

const REPRO_SCRIPT = `/**
 * GENERATED by tools/ircv/counterexample-reproducer.ts — adversarial execution.
 * Scenario: old identity epoch accepted after revocation.
 * Runs the TS RCLB gate, the local x402 facilitator, and verifyTrace R18.
 */
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import {
  TEST_KEYS,
  buildValidBundle,
  descriptor,
  shopperAddress,
  verifyTrace,
} from "@clb-acel/attack-core";
import {
  checkRevocationAwareAcceptance,
  computeCommitment,
  computeMandateDigest,
  computeRevocationAwareCommitment,
  deriveRevocationAwareNonce,
} from "@clb-acel/clb-core";
import {
  buildPaymentAuthorization,
  createLocalFacilitator,
  signPaymentPayload,
} from "@clb-acel/x402-adapter";
import { type Hex, keccak256, toBytes } from "viem";
import { privateKeyToAccount } from "viem/accounts";

const fields = {
  baseCommitment: keccak256(toBytes("rclb-demo-base-commitment-v1")),
  identityEpoch: 1n,
  mandateEpoch: 1n,
  expiry: 1800000000n,
  nonce: \`0x\${"11".repeat(32)}\` as Hex,
};
const commitment = computeRevocationAwareCommitment(fields);
const paymentNonce = deriveRevocationAwareNonce(commitment);

// 1. Local facilitator: accepts a well-formed payment with the stale C_t nonce.
const payload = await signPaymentPayload(
  TEST_KEYS.shopperKey,
  buildPaymentAuthorization({ from: shopperAddress, descriptor: descriptor(), nonce: paymentNonce }),
);
const receipt = await createLocalFacilitator().settle(payload);

// 2. TS RCLB gate with the CURRENT authority state after identity revocation.
const acceptance = checkRevocationAwareAcceptance({
  fields,
  commitment,
  currentIdentityEpoch: 2n,
  currentMandateEpoch: 1n,
  now: 1700000000n,
});

// 3. verifier-core R18 gate on an existing honest trace bundle.
const bundle = await buildValidBundle({ traceId: "ircv-cex-stale-epoch" });
const base = computeCommitment({
  identityRef: bundle.clb.identityRef,
  mandateDigest: computeMandateDigest(bundle.mandate),
  settlementDescriptor: bundle.clb.settlementDescriptor,
  domain: bundle.clb.domain,
});
const verification = await verifyTrace(bundle, {
  expectedHumanPrincipal: privateKeyToAccount(TEST_KEYS.userKey).address,
  revocationBinding: {
    baseCommitment: base,
    commitment,
    identityEpoch: fields.identityEpoch,
    mandateEpoch: fields.mandateEpoch,
    expiry: fields.expiry,
    nonce: fields.nonce,
    now: 1700000000n,
    current: { identityEpoch: 2n, mandateEpoch: 1n },
  },
});

const result = {
  scenarioId: "SETTLE_AFTER_IDENTITY_REVOCATION",
  expectedRejected: true,
  actualRejected: !acceptance.ok &&
    verification.result.failedRules.includes("R18_REVOCATION_AWARE_BINDING"),
  acceptanceOk: acceptance.ok,
  acceptanceDetail: acceptance.detail,
  acceptanceViolations: acceptance.violations,
  facilitatorAccepted: receipt.settled,
  verifierStatus: verification.result.status,
  verifierFailedRules: verification.result.failedRules,
  paymentNonce,
};

const outPath = resolve(import.meta.dir, "counterexample-execution.json");
await writeFile(outPath, JSON.stringify(result, null, 2), "utf8");
console.log(JSON.stringify(result));
`;

export type CounterexampleReport = {
  schema: "ircv-counterexample/v1";
  status: "PASS" | "FAIL" | "NOT RUNNABLE";
  source: string;
  parsedScenario: string | null;
  expectedRejection: boolean | null;
  actualRejection: boolean | null;
  generatedScript: string;
  execution: {
    acceptanceViolations: string[];
    facilitatorAccepted: boolean | null;
    verifierFailedRules: string[];
    verifierStatus: string | null;
    paymentNonce: string | null;
    stdout: string;
  };
  finding: string;
  reason?: string;
};

export async function reproduceCounterexample(): Promise<CounterexampleReport> {
  const inputFile = process.env.IRCV_COUNTEREXAMPLE_FILE;
  const description = inputFile
    ? await readFile(resolve(inputFile), "utf8")
    : BUILTIN_COUNTEREXAMPLE;
  const source = inputFile ?? "built-in sample";
  const parsedScenario = /identity epoch/i.test(description) && /revocation/i.test(description)
    ? "SETTLE_AFTER_IDENTITY_REVOCATION"
    : null;

  await writeFile(resolve(ARTIFACT_DIR, "counterexample.txt"), description, "utf8");

  if (parsedScenario === null) {
    return {
      schema: "ircv-counterexample/v1",
      status: "NOT RUNNABLE",
      source,
      parsedScenario: null,
      expectedRejection: null,
      actualRejection: null,
      generatedScript: "",
      execution: {
        acceptanceViolations: [],
        facilitatorAccepted: null,
        verifierFailedRules: [],
        verifierStatus: null,
        paymentNonce: null,
        stdout: "",
      },
      finding: "No executable scenario could be parsed from the supplied description.",
      reason: "Built-in RCLB scenario requires 'identity epoch' and 'revocation' in the description.",
    };
  }

  const scriptPath = resolve(ARTIFACT_DIR, "reproduce-stale-identity-epoch.ts");
  await writeFile(scriptPath, REPRO_SCRIPT, "utf8");

  const proc = Bun.spawnSync({
    cmd: [process.execPath, "run", scriptPath],
    cwd: resolve(ARTIFACT_DIR, "../../.."),
    stdout: "pipe",
    stderr: "pipe",
  });
  const stdout = new TextDecoder().decode(proc.stdout);
  if (proc.exitCode !== 0) {
    return {
      schema: "ircv-counterexample/v1",
      status: "NOT RUNNABLE",
      source,
      parsedScenario,
      expectedRejection: true,
      actualRejection: null,
      generatedScript: scriptPath,
      execution: {
        acceptanceViolations: [],
        facilitatorAccepted: null,
        verifierFailedRules: [],
        verifierStatus: null,
        paymentNonce: null,
        stdout,
      },
      finding: "Generated script failed to execute.",
      reason: new TextDecoder().decode(proc.stderr).slice(-2000),
    };
  }

  const execution = JSON.parse(
    await readFile(resolve(ARTIFACT_DIR, "counterexample-execution.json"), "utf8"),
  ) as {
    expectedRejected: boolean;
    actualRejected: boolean;
    acceptanceViolations: string[];
    facilitatorAccepted: boolean;
    verifierStatus: string;
    verifierFailedRules: string[];
    paymentNonce: string;
  };

  return {
    schema: "ircv-counterexample/v1",
    status: execution.expectedRejected === execution.actualRejected ? "PASS" : "FAIL",
    source,
    parsedScenario,
    expectedRejection: execution.expectedRejected,
    actualRejection: execution.actualRejected,
    generatedScript: scriptPath,
    execution: {
      acceptanceViolations: execution.acceptanceViolations,
      facilitatorAccepted: execution.facilitatorAccepted,
      verifierFailedRules: execution.verifierFailedRules,
      verifierStatus: execution.verifierStatus,
      paymentNonce: execution.paymentNonce,
      stdout,
    },
    finding:
      "The local x402 facilitator accepts the stale C_t payment nonce; rejection comes from the opt-in R18 RCLB gate (IDENTITY_EPOCH_STALE). RCLB is absent from clb-aligned.spthy, so this counterexample is executable but outside the formal model's alphabet.",
  };
}
